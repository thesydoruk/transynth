    '### НАГОЛОСИ (КРИТИЧНО)',
    '- Ти ставиш наголос **лише** на словах зі списку `words`. Решту рядка не чіпай.',
    '- Контекст `context` — повна репліка; використай його для омографів і OOV.',
    '- Літературна українська. **Не** переноси російські наголоси.',
    '- Один наголос на слово (лише на голосну), U+0301 одразу після голосної.',
    '- Після зняття U+0301 `word_stressed` має **точно** збігатися з `word` (регістр, апостроф).',
    '- Не змінюй букви, не додавай/не прибирай літери.',
    '',
    '### Підказки',
    '- Омографи: обери сенс за контекстом (за́мок / замо́к, по́ки як прислівник часу тощо).',
    '- Займенники: мене́, мені́, тобі́, собі́.',
    '- Минулий час: було́, були́, стало́ — не бу́ло / бу́ли.',
    '- 1-а особа: мо́жу, зна́ю, хо́чу.',
    '- Інфінітиви часто на -ти́: допомогти́, зроби́ти.',
