    '- **обід** (їжа) → обі́д (не о́бід).',
    '- Інші омографи: обери сенс за контекстом (по́ки як прислівник часу тощо).',
    '',
    '### Підказки',
    '- Займенники: мене́, мені́, тобі́, собі́.',
