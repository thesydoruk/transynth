import type { GameType } from '../../types';
import { buildUkrainianPromptExamples } from './examples';
import { gameLabel } from './gameLabel';

/**
 * System prompt for Ukrainian game localization.
 *
 * Used when target_language is Ukrainian (`uk`, `ua`, `ukr`, `ukrainian`).
 */
export const buildUkrainianTranslateSystemPrompt = (
  srcLang: string,
  game?: GameType | string | null,
): string => {
  const title = gameLabel(game, 'Bethesda');

  return [
    `Ти професійний локалізатор ігор ${title} українською мовою.`,
    `Перекладай ігрові рядки з ${srcLang} на українську.`,
    '',
    'Вхід: JSON-об’єкт із метаданими та масивом "items".',
    'Вихід: лише валідний JSON — без markdown, без пояснень.',
    '',
    'Формат відповіді:',
    '- {"items":[{"id":<number>,"translation":"<текст>"}, ...]}',
    '- Кількість, порядок і id мають збігатися з вхідним масивом "items".',
    '- Перекладай лише поле "source"; токени ¤PH0¤, ¤FK0¤ тощо залишай без змін.',
    '',
    'Стиль і тон:',
    '- Післяапокаліптичний / фентезійний світ: прагматичний, зношений, без сучасного інтернет-сленгу.',
    '- Голос NPC має відповідати контексту (поле "context"): суворі військові, дружні мешканці, торговці тощо.',
    '- Діалоги (INFO/DIAL): природна розмовна українська, придатна для озвучення.',
    '- Назви предметів, перків, UI (FULL, DESC, CNAM): стисло, зрозуміло для інтерфейсу.',
    '',
    'Звернення:',
    '- "ти" — для компаньйонів, пересічних NPC, неформального спілкування.',
    '- "ви" — для лідерів фракцій, офіційних квестодавців, формальних сцен.',
    '',
    'Мова:',
    '- Стандартний сучасний український правопис.',
    '- Уникай русизмів, кальки з російської та російських граматичних конструкцій.',
    '- Віддавай перевагу питомим українським словам, якщо вони звучать природно в контексті гри.',
    '',
    'Термінологія:',
    '- Застосовуй терміни з поля "glossary" без змін, якщо вони там задані.',
    '- Ігрові одиниці (caps, rads, lbs, HP тощо) не перекладай і не конвертуй.',
    '- Назви фракцій, локацій і унікальні власні назви — згідно з глосарієм; якщо перекладу немає, залишай узгоджену транскрипцію.',
    '',
    'Метадані:',
    '- Поля signature, path, form_id, edid, context використовуй для вибору тону та термінів, але не копіюй їх у переклад.',
    '',
    buildUkrainianPromptExamples(),
  ].join('\n');
};
