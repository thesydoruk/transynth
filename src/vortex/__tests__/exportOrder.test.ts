import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { mergeLangpackEntries } from '../../web/export/langpackMerge';
import { parseVortexDeployment } from '../deploymentManifest';
import {
  discoverVortexExportOrder,
  filterVortexLangpackMods,
  orderVortexLangpackModIds,
} from '../exportOrder';
import { parsePluginList } from '../pluginsTxt';

describe('parsePluginList', () => {
  it('reads load order and starred enabled plugins', () => {
    const parsed = parsePluginList(`# Automatically generated by Vortex
Fallout4.esm
DLCRobot.esm
*unofficial fallout 4 patch.esp
M8rDisablePipboyEffects.esp
`);
    expect(parsed.plugins).toEqual([
      'Fallout4.esm',
      'DLCRobot.esm',
      'unofficial fallout 4 patch.esp',
      'M8rDisablePipboyEffects.esp',
    ]);
    expect(parsed.enabled).toEqual(['unofficial fallout 4 patch.esp']);
  });
});

describe('parseVortexDeployment', () => {
  it('keeps the first winner per path', () => {
    const files = parseVortexDeployment({
      files: [
        { relPath: 'Interface\\PipboyMenu.swf', source: 'FallUI VR-Patch' },
        { relPath: 'Data/Interface/PipboyMenu.swf', source: 'FallUI Inventory' },
        { relPath: 'Interface/Translate_en.txt', source: 'FallUI VR-Patch' },
      ],
    });
    expect(files).toEqual([
      { relPath: 'Interface/PipboyMenu.swf', sourceFolder: 'FallUI VR-Patch' },
      { relPath: 'Interface/Translate_en.txt', sourceFolder: 'FallUI VR-Patch' },
    ]);
  });
});

describe('filterVortexLangpackMods', () => {
  const rows = [
    {
      id: 1,
      name: 'Fallout4',
      channel: 'game',
      abs_path: 'C:/game/Data/Fallout4.esm',
      source_folder: null,
    },
    {
      id: 2,
      name: 'UFO4P',
      channel: 'mods',
      abs_path: 'C:/mods/unofficial fallout 4 patch.esp',
      source_folder: 'Unofficial Fallout 4 Patch',
    },
    {
      id: 3,
      name: 'Disabled Patch',
      channel: 'mods',
      abs_path: 'C:/mods/Disabled.esp',
      source_folder: 'Disabled Patch-1-1',
      pluginFileName: 'Disabled.esp',
    },
    {
      id: 4,
      name: 'FallUI HUD',
      channel: 'mods',
      abs_path: null,
      source_folder: 'FallUI - HUD-51813',
    },
  ];

  it('keeps game and deployed staging folders, ignoring plugins.txt stars', () => {
    const kept = filterVortexLangpackMods(rows, {
      plugins: ['Fallout4.esm', 'unofficial fallout 4 patch.esp', 'Disabled.esp'],
      enabledPlugins: ['unofficial fallout 4 patch.esp'],
      fileWinners: [
        { path: 'unofficial fallout 4 patch.esp', sourceFolder: 'Unofficial Fallout 4 Patch' },
        { path: 'Interface/HUDMenu.swf', sourceFolder: 'FallUI - HUD-51813' },
        { path: 'Disabled.esp', sourceFolder: 'Disabled Patch-1-1' },
      ],
    });
    expect(kept.map((row) => row.id)).toEqual([1, 2, 3, 4]);
  });

  it('drops a staging mod whose folder is not in the deployment', () => {
    const kept = filterVortexLangpackMods(rows, {
      plugins: ['Fallout4.esm', 'Disabled.esp'],
      enabledPlugins: ['Disabled.esp'],
      fileWinners: [
        { path: 'unofficial fallout 4 patch.esp', sourceFolder: 'Unofficial Fallout 4 Patch' },
      ],
    });
    expect(kept.map((row) => row.id)).toEqual([1, 2]);
  });
});

