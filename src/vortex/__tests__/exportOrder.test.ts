describe('mergeLangpackEntries file winners', () => {
  it('keeps the Vortex winner even when a later mod wrote the same path', () => {
    const merged = mergeLangpackEntries(
      [
        {
          entry: { name: 'Interface/PipboyMenu.swf', data: Buffer.from('inventory') },
          sourceFolder: 'FallUI - Inventory-48758-2-2-1-1666954336',
        },
        {
          entry: { name: 'Interface/PipboyMenu.swf', data: Buffer.from('vr') },
          sourceFolder: '(Experimental) FallUI VR-Patch-48758-1-12-1-vr-exp3-1618625274',
        },
      ],
      [
        {
          path: 'Interface/PipboyMenu.swf',
          sourceFolder: '(Experimental) FallUI VR-Patch-48758-1-12-1-vr-exp3-1618625274',
        },
      ],
    );
    expect(merged).toHaveLength(1);
    expect(merged[0]?.data?.toString()).toBe('vr');
  });

  it('keeps en and ru winners on their own paths', () => {
    const merged = mergeLangpackEntries(
      [
        {
          entry: {
            name: 'Interface/FallUI HUD/Translation/Translate_en.txt',
            data: Buffer.from('hud-en'),
          },
          sourceFolder: 'FallUI - HUD-51813',
        },
        {
          entry: {
            name: 'Interface/FallUI HUD/Translation/Translate_ru.txt',
            data: Buffer.from('hud-ru-from-en'),
          },
          sourceFolder: 'FallUI - HUD-51813',
        },
        {
          entry: {
            name: 'Interface/FallUI HUD/Translation/Translate_ru.txt',
            data: Buffer.from('hud-ru-pack'),
          },
          sourceFolder: 'FallUI HUD - RU-51827',
        },
      ],
      [
        {
          path: 'Interface/FallUI HUD/Translation/Translate_en.txt',
          sourceFolder: 'FallUI - HUD-51813',
        },
        {
          path: 'Interface/FallUI HUD/Translation/Translate_ru.txt',
          sourceFolder: 'FallUI HUD - RU-51827',
        },
      ],
    );
    const byName = Object.fromEntries(merged.map((file) => [file.name, file.data?.toString()]));
    expect(byName['Interface/FallUI HUD/Translation/Translate_en.txt']).toBe('hud-en');
    expect(byName['Interface/FallUI HUD/Translation/Translate_ru.txt']).toBe('hud-ru-pack');
  });
});

describe('discoverVortexExportOrder', () => {
  it('reads loadorder.txt and vortex.deployment.json next to staging', () => {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'vortex-order-'));
    try {
      const staging = path.join(root, 'mods');
      fs.mkdirSync(staging, { recursive: true });
      fs.writeFileSync(
        path.join(root, 'loadorder.txt'),
        '# test\nFallout4.esm\nunofficial fallout 4 patch.esp\n',
      );
      fs.writeFileSync(
        path.join(staging, 'vortex.deployment.json'),
        JSON.stringify({
          deploymentMethod: 'hardlink_activator',
          files: [
            {
              relPath: 'Interface\\Translate_en.txt',
              source: '(Experimental) FallUI VR-Patch-48758-1-12-1-vr-exp3-1618625274',
            },
          ],
        }),
      );
      const found = discoverVortexExportOrder({
        game: 'fo4',
        stagingPath: staging,
        pluginsTxt: path.join(root, 'loadorder.txt'),
      });
      expect(found.plugins[0]).toBe('Fallout4.esm');
      expect(found.plugins).toContain('unofficial fallout 4 patch.esp');
      expect(found.fileWinners).toEqual([
        {
          path: 'Interface/Translate_en.txt',
          sourceFolder: '(Experimental) FallUI VR-Patch-48758-1-12-1-vr-exp3-1618625274',
        },
      ]);
    } finally {
      fs.rmSync(root, { recursive: true, force: true });
    }
  });
});
